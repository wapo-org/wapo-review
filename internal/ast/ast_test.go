package ast

import "testing"

func TestParseSupportedLanguages(t *testing.T) {
	cases := map[string]string{
		"a.ts":   "export function run() { return 1 }",
		"a.mts":  "export function run() { return 1 }",
		"a.cts":  "export function run() { return 1 }",
		"a.tsx":  "export const View = () => <div />",
		"a.py":   "def run():\n    return 1\n",
		"a.go":   "package p\nfunc Run() int { return 1 }",
		"a.rs":   "pub fn run() -> i32 { 1 }",
		"a.java": "class A { void run() {} }",
	}
	for path, src := range cases {
		t.Run(path, func(t *testing.T) {
			if _, err := Parse(path, []byte(src)); err != nil {
				t.Fatal(err)
			}
		})
	}
}

func TestGeneratedExclusion(t *testing.T) {
	if !IsExcluded("src/gen.go", []string{"// Code generated by tool. DO NOT EDIT."}, nil, nil).Excluded {
		t.Fatal("generated header was not excluded")
	}
}

func TestExtractTypedInvariantFacts(t *testing.T) {
	facts, err := ExtractFileFacts("src/jobs.ts", []byte(`db.query("jobs"); db.insert("jobs", value); defineTable({ events: schema }); SELECT * FROM jobs; const state = "pending";`))
	if err != nil {
		t.Fatal(err)
	}
	if len(facts.Tables) != 2 || facts.Tables[0] != "events" || facts.Tables[1] != "jobs" {
		t.Fatalf("unexpected tables: %v", facts.Tables)
	}
	if len(facts.Statuses) != 1 || facts.Statuses[0] != "pending" {
		t.Fatalf("unexpected statuses: %v", facts.Statuses)
	}
}
